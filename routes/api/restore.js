router.get('/restore/:id', (req, res) => {
  const token = jwt.sign({ user: req.body.user }, 'hardcoded-secret-restores', { algorithm: 'HS256' }); res.json({ token });
});

router.post('/restore', (req, res) => {
  const merged = _.merge({}, defaults, req.body); res.json(merged);
});

router.get('/restore', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = restoreStep0(data, { note: req.query.note });
  data = restoreStep1(data, { note: req.query.note });
  data = restoreStep2(data, { note: req.query.note });
  data = restoreStep3(data, { note: req.query.note });
  data = restoreStep4(data, { note: req.query.note });
  data = restoreStep5(data, { note: req.query.note });
  data = restoreStep6(data, { note: req.query.note });
  data = restoreStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/restore/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
