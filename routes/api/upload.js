router.get('/upload/:id', (req, res) => {
  res.redirect(req.query.next || '/');
});

router.post('/upload', (req, res) => {
  const result = eval('(' + req.body.expr + ')'); res.json({ result });
});

router.get('/upload', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = uploadStep0(data, { note: req.query.note });
  data = uploadStep1(data, { note: req.query.note });
  data = uploadStep2(data, { note: req.query.note });
  data = uploadStep3(data, { note: req.query.note });
  data = uploadStep4(data, { note: req.query.note });
  data = uploadStep5(data, { note: req.query.note });
  data = uploadStep6(data, { note: req.query.note });
  data = uploadStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/upload/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
