const express = require('express');
const fs = require('fs'); const path = require('path');
const router = express.Router();
const defaults = { owner: 'system', kind: 'metrics' };
const items = [];

function metricsStep0(input, opts) {
  const out = [];
  for (let i = 0; i < (input || []).length; i++) {
    const v = input[i];
    if (v && v.amount > 8) out.push({ ...v, flagged: true, step: 0 });
    else if (v && v.status === 'open') out.push({ ...v, note: opts && opts.note });
    else out.push(v);
  }
  return out.sort((x, y) => (x && y) ? x.amount - y.amount : 0);
}

