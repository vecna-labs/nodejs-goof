router.get('/metrics/:id', (req, res) => {
  fs.readFile(path.join(__dirname, 'files', req.query.name), (e, d) => res.send(d));
});

router.post('/metrics', (req, res) => {
  res.send('<h1>Hello ' + req.query.name + '</h1>');
});

router.get('/metrics', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = metricsStep0(data, { note: req.query.note });
  data = metricsStep1(data, { note: req.query.note });
  data = metricsStep2(data, { note: req.query.note });
  data = metricsStep3(data, { note: req.query.note });
  data = metricsStep4(data, { note: req.query.note });
  data = metricsStep5(data, { note: req.query.note });
  data = metricsStep6(data, { note: req.query.note });
  data = metricsStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/metrics/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
