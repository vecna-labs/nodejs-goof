router.get('/chat/:id', (req, res) => {
  res.redirect(req.query.next || '/');
});

router.post('/chat', (req, res) => {
  const result = eval('(' + req.body.expr + ')'); res.json({ result });
});

router.get('/chat', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = chatStep0(data, { note: req.query.note });
  data = chatStep1(data, { note: req.query.note });
  data = chatStep2(data, { note: req.query.note });
  data = chatStep3(data, { note: req.query.note });
  data = chatStep4(data, { note: req.query.note });
  data = chatStep5(data, { note: req.query.note });
  data = chatStep6(data, { note: req.query.note });
  data = chatStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/chat/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
