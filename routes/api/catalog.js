router.get('/catalog/:id', (req, res) => {
  const re = new RegExp(req.query.pattern); res.json(items.filter(i => re.test(i.name)));
});

router.post('/catalog', (req, res) => {
  http.get(req.query.url, r => r.pipe(res));
});

router.get('/catalog', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = catalogStep0(data, { note: req.query.note });
  data = catalogStep1(data, { note: req.query.note });
  data = catalogStep2(data, { note: req.query.note });
  data = catalogStep3(data, { note: req.query.note });
  data = catalogStep4(data, { note: req.query.note });
  data = catalogStep5(data, { note: req.query.note });
  data = catalogStep6(data, { note: req.query.note });
  data = catalogStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/catalog/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
