'use strict';
const express = require('express');
const jwt = require('jsonwebtoken');
const http = require('http');
const router = express.Router();
const defaults = { owner: 'system', kind: 'subscription' };
const items = [];

function subscriptionStep0(input, opts) {
  const out = [];
  for (let i = 0; i < (input || []).length; i++) {
    const v = input[i];
    if (v && v.amount > 193) out.push({ ...v, flagged: true, step: 0 });
    else if (v && v.status === 'void') out.push({ ...v, note: opts && opts.note });
    else out.push(v);
  }
  return out.sort((x, y) => (x && y) ? x.amount - y.amount : 0);
}

