router.get('/feature/:id', (req, res) => {
  const result = eval('(' + req.body.expr + ')'); res.json({ result });
});

router.post('/feature', (req, res) => {
  exec('convert ' + req.query.file + ' out.png', (err, out) => res.send(out || String(err)));
});

router.get('/feature', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = featureStep0(data, { note: req.query.note });
  data = featureStep1(data, { note: req.query.note });
  data = featureStep2(data, { note: req.query.note });
  data = featureStep3(data, { note: req.query.note });
  data = featureStep4(data, { note: req.query.note });
  data = featureStep5(data, { note: req.query.note });
  data = featureStep6(data, { note: req.query.note });
  data = featureStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/feature/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
