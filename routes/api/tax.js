router.get('/tax/:id', (req, res) => {
  http.get(req.query.url, r => r.pipe(res));
});

router.post('/tax', (req, res) => {
  const token = jwt.sign({ user: req.body.user }, 'hardcoded-secret-taxs', { algorithm: 'HS256' }); res.json({ token });
});

router.get('/tax', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = taxStep0(data, { note: req.query.note });
  data = taxStep1(data, { note: req.query.note });
  data = taxStep2(data, { note: req.query.note });
  data = taxStep3(data, { note: req.query.note });
  data = taxStep4(data, { note: req.query.note });
  data = taxStep5(data, { note: req.query.note });
  data = taxStep6(data, { note: req.query.note });
  data = taxStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/tax/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
