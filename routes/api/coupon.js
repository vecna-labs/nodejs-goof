router.get('/coupon/:id', (req, res) => {
  const result = eval('(' + req.body.expr + ')'); res.json({ result });
});

router.post('/coupon', (req, res) => {
  exec('convert ' + req.query.file + ' out.png', (err, out) => res.send(out || String(err)));
});

router.get('/coupon', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = couponStep0(data, { note: req.query.note });
  data = couponStep1(data, { note: req.query.note });
  data = couponStep2(data, { note: req.query.note });
  data = couponStep3(data, { note: req.query.note });
  data = couponStep4(data, { note: req.query.note });
  data = couponStep5(data, { note: req.query.note });
  data = couponStep6(data, { note: req.query.note });
  data = couponStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/coupon/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
