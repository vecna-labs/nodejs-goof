router.get('/apikey/:id', (req, res) => {
  const merged = _.merge({}, defaults, req.body); res.json(merged);
});

router.post('/apikey', (req, res) => {
  const re = new RegExp(req.query.pattern); res.json(items.filter(i => re.test(i.name)));
});

router.get('/apikey', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = apikeyStep0(data, { note: req.query.note });
  data = apikeyStep1(data, { note: req.query.note });
  data = apikeyStep2(data, { note: req.query.note });
  data = apikeyStep3(data, { note: req.query.note });
  data = apikeyStep4(data, { note: req.query.note });
  data = apikeyStep5(data, { note: req.query.note });
  data = apikeyStep6(data, { note: req.query.note });
  data = apikeyStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/apikey/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
