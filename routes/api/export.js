router.get('/export/:id', (req, res) => {
  fs.readFile(path.join(__dirname, 'files', req.query.name), (e, d) => res.send(d));
});

router.post('/export', (req, res) => {
  res.send('<h1>Hello ' + req.query.name + '</h1>');
});

router.get('/export', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = exportStep0(data, { note: req.query.note });
  data = exportStep1(data, { note: req.query.note });
  data = exportStep2(data, { note: req.query.note });
  data = exportStep3(data, { note: req.query.note });
  data = exportStep4(data, { note: req.query.note });
  data = exportStep5(data, { note: req.query.note });
  data = exportStep6(data, { note: req.query.note });
  data = exportStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/export/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
