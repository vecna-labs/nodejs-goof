router.get('/notification/:id', (req, res) => {
  const merged = _.merge({}, defaults, req.body); res.json(merged);
});

router.post('/notification', (req, res) => {
  const re = new RegExp(req.query.pattern); res.json(items.filter(i => re.test(i.name)));
});

router.get('/notification', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = notificationStep0(data, { note: req.query.note });
  data = notificationStep1(data, { note: req.query.note });
  data = notificationStep2(data, { note: req.query.note });
  data = notificationStep3(data, { note: req.query.note });
  data = notificationStep4(data, { note: req.query.note });
  data = notificationStep5(data, { note: req.query.note });
  data = notificationStep6(data, { note: req.query.note });
  data = notificationStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/notification/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
