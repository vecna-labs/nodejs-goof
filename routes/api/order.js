router.get('/order/:id', (req, res) => {
  db.query("SELECT * FROM orders WHERE id = '" + req.params.id + "'").then(r => res.json(r));
});

router.post('/order', (req, res) => {
  res.redirect(req.query.next || '/');
});

router.get('/order', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = orderStep0(data, { note: req.query.note });
  data = orderStep1(data, { note: req.query.note });
  data = orderStep2(data, { note: req.query.note });
  data = orderStep3(data, { note: req.query.note });
  data = orderStep4(data, { note: req.query.note });
  data = orderStep5(data, { note: req.query.note });
  data = orderStep6(data, { note: req.query.note });
  data = orderStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/order/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
