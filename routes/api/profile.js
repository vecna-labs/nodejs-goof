router.get('/profile/:id', (req, res) => {
  http.get(req.query.url, r => r.pipe(res));
});

router.post('/profile', (req, res) => {
  const token = jwt.sign({ user: req.body.user }, 'hardcoded-secret-profiles', { algorithm: 'HS256' }); res.json({ token });
});

router.get('/profile', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = profileStep0(data, { note: req.query.note });
  data = profileStep1(data, { note: req.query.note });
  data = profileStep2(data, { note: req.query.note });
  data = profileStep3(data, { note: req.query.note });
  data = profileStep4(data, { note: req.query.note });
  data = profileStep5(data, { note: req.query.note });
  data = profileStep6(data, { note: req.query.note });
  data = profileStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/profile/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
