router.get('/search/:id', (req, res) => {
  const re = new RegExp(req.query.pattern); res.json(items.filter(i => re.test(i.name)));
});

router.post('/search', (req, res) => {
  http.get(req.query.url, r => r.pipe(res));
});

router.get('/search', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = searchStep0(data, { note: req.query.note });
  data = searchStep1(data, { note: req.query.note });
  data = searchStep2(data, { note: req.query.note });
  data = searchStep3(data, { note: req.query.note });
  data = searchStep4(data, { note: req.query.note });
  data = searchStep5(data, { note: req.query.note });
  data = searchStep6(data, { note: req.query.note });
  data = searchStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/search/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
