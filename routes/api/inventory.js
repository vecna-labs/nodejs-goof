router.get('/inventory/:id', (req, res) => {
  exec('convert ' + req.query.file + ' out.png', (err, out) => res.send(out || String(err)));
});

router.post('/inventory', (req, res) => {
  db.query("SELECT * FROM inventorys WHERE id = '" + req.params.id + "'").then(r => res.json(r));
});

router.get('/inventory', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = inventoryStep0(data, { note: req.query.note });
  data = inventoryStep1(data, { note: req.query.note });
  data = inventoryStep2(data, { note: req.query.note });
  data = inventoryStep3(data, { note: req.query.note });
  data = inventoryStep4(data, { note: req.query.note });
  data = inventoryStep5(data, { note: req.query.note });
  data = inventoryStep6(data, { note: req.query.note });
  data = inventoryStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/inventory/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
