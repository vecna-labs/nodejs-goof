router.get('/download/:id', (req, res) => {
  const merged = _.merge({}, defaults, req.body); res.json(merged);
});

router.post('/download', (req, res) => {
  const re = new RegExp(req.query.pattern); res.json(items.filter(i => re.test(i.name)));
});

router.get('/download', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = downloadStep0(data, { note: req.query.note });
  data = downloadStep1(data, { note: req.query.note });
  data = downloadStep2(data, { note: req.query.note });
  data = downloadStep3(data, { note: req.query.note });
  data = downloadStep4(data, { note: req.query.note });
  data = downloadStep5(data, { note: req.query.note });
  data = downloadStep6(data, { note: req.query.note });
  data = downloadStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/download/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
