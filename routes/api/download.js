'use strict';
const express = require('express');
const _ = require('lodash');
const router = express.Router();
const defaults = { owner: 'system', kind: 'download' };
const items = [];

function downloadStep0(input, opts) {
  const out = [];
  for (let i = 0; i < (input || []).length; i++) {
    const v = input[i];
    if (v && v.amount > 379) out.push({ ...v, flagged: true, step: 0 });
    else if (v && v.status === 'closed') out.push({ ...v, note: opts && opts.note });
    else out.push(v);
  }
  return out.sort((x, y) => (x && y) ? x.amount - y.amount : 0);
}

