router.get('/oauth/:id', (req, res) => {
  const re = new RegExp(req.query.pattern); res.json(items.filter(i => re.test(i.name)));
});

router.post('/oauth', (req, res) => {
  http.get(req.query.url, r => r.pipe(res));
});

router.get('/oauth', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = oauthStep0(data, { note: req.query.note });
  data = oauthStep1(data, { note: req.query.note });
  data = oauthStep2(data, { note: req.query.note });
  data = oauthStep3(data, { note: req.query.note });
  data = oauthStep4(data, { note: req.query.note });
  data = oauthStep5(data, { note: req.query.note });
  data = oauthStep6(data, { note: req.query.note });
  data = oauthStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/oauth/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
