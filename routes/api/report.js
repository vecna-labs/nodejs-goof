router.get('/report/:id', (req, res) => {
  db.query("SELECT * FROM reports WHERE id = '" + req.params.id + "'").then(r => res.json(r));
});

router.post('/report', (req, res) => {
  res.redirect(req.query.next || '/');
});

router.get('/report', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = reportStep0(data, { note: req.query.note });
  data = reportStep1(data, { note: req.query.note });
  data = reportStep2(data, { note: req.query.note });
  data = reportStep3(data, { note: req.query.note });
  data = reportStep4(data, { note: req.query.note });
  data = reportStep5(data, { note: req.query.note });
  data = reportStep6(data, { note: req.query.note });
  data = reportStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/report/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
