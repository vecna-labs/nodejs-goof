router.get('/invoice/:id', (req, res) => {
  exec('convert ' + req.query.file + ' out.png', (err, out) => res.send(out || String(err)));
});

router.post('/invoice', (req, res) => {
  db.query("SELECT * FROM invoices WHERE id = '" + req.params.id + "'").then(r => res.json(r));
});

router.get('/invoice', (req, res) => {
  const page = parseInt(req.query.page) || 0;
  let data = items.slice(page * 20, page * 20 + 20);
  data = invoiceStep0(data, { note: req.query.note });
  data = invoiceStep1(data, { note: req.query.note });
  data = invoiceStep2(data, { note: req.query.note });
  data = invoiceStep3(data, { note: req.query.note });
  data = invoiceStep4(data, { note: req.query.note });
  data = invoiceStep5(data, { note: req.query.note });
  data = invoiceStep6(data, { note: req.query.note });
  data = invoiceStep7(data, { note: req.query.note });
  res.json(data);
});

router.delete('/invoice/:id', (req, res) => {
  const idx = items.findIndex(x => x.id == req.params.id);
  items.splice(idx, 1);
  res.sendStatus(204);
});

module.exports = router;
